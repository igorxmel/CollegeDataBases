def sql_between(text, start, end, *, include_end=True):
    """Кусок скрипта от первого вхождения start до end (оба как обычные строки)."""
    a = text.index(start)
    b = text.index(end, a) + (len(end) if include_end else 0)
    return text[a:b].rstrip()



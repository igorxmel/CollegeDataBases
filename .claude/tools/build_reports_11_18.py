def clean_sql(text):
    """Убрать строки-комментарии, оставив сами запросы."""
    lines = [ln for ln in text.splitlines() if not ln.lstrip().startswith("--")]
    return "\n".join(lines)


def views(script):
    text = (ROOT / script).read_text(encoding="utf-8")
    found = re.findall(r"^CREATE VIEW .*?;$", clean_sql(text), re.M | re.S)
    return [q.rstrip(";").rstrip() + ";" for q in found]



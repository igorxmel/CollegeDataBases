def commands_18():
    """Команды из файла решения, по пунктам: блоки разделены строкой с номером."""
    blocks, current = {}, None
    for line in COMMANDS_18.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^:: (\d)\.", line)
        if m:
            current = int(m.group(1))
            blocks[current] = []
        elif current and line.strip() and not line.startswith("::"):
            blocks[current].append(line)
    return {k: "\n".join(v) for k, v in blocks.items()}



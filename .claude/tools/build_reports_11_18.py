def procedure(script_text, name):
    m = re.search(rf"^CREATE PROCEDURE {name}\(.*?^END\$\$", script_text, re.M | re.S)
    if not m:
        raise SystemExit(f"процедура {name} не найдена")
    return "DELIMITER $$\n" + m.group(0) + "\nDELIMITER ;"



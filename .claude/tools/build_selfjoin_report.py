def read_queries():
    text = SCRIPT.read_text(encoding="utf-8")
    found = re.findall(r"^CREATE VIEW .*?;$", text, re.M | re.S)
    return [q.rstrip(";").rstrip() + ";" for q in found]


def build():
    queries = read_queries()
    if len(queries) != len(TASKS):
        raise SystemExit(f"запросов {len(queries)}, пунктов задания {len(TASKS)}")

    doc = rb.new_document()
    rb.title_page(doc, 10, TOPIC)

    rb.heading(doc, "1", "Цель работы")
    rb.para(doc, GOAL)

    rb.heading(doc, "2", "Задание")
    rb.para(doc, "Ответить на вопросы теоретической части и выполнить семь запросов "
                 "практической части. Результат каждого запроса сохранить в "
                 "представление.")

    rb.heading(doc, "3", "Ответы на вопросы теоретической части")
    for i, (question, answer) in enumerate(THEORY, start=1):
        rb.para(doc, f"{i} {question}")
        rb.para(doc, answer)
        rb.blank(doc)

    rb.heading(doc, "4", "Практическая часть")
    for i, (task, query) in enumerate(zip(TASKS, queries), start=1):
        rb.para(doc, f"{i}. {task}")
        rb.blank(doc)
        rb.code(doc, query)
        rb.blank(doc)

    rb.heading(doc, "5", "Вывод")
    for text in CONCLUSION:
        rb.para(doc, text)

    rb.save(doc, OUT)


if __name__ == "__main__":
    build()

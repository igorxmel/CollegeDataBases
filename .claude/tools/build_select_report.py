def read_queries(filename):
    """Достать из файла решения тексты CREATE VIEW по порядку."""
    text = (SOLUTION / filename).read_text(encoding="utf-8")
    found = re.findall(r"^CREATE VIEW .*?;$", text, re.M | re.S)
    return [q.rstrip(";").rstrip() + ";" for q in found]


def build():
    doc = rb.new_document()
    rb.title_page(doc, 7, TOPIC)

    rb.heading(doc, "1", "Цель работы")
    rb.para(doc, GOAL)

    rb.heading(doc, "2", "Задание")
    for i, text in enumerate(TASKS, start=1):
        rb.para(doc, f"{i}. {text}")

    rb.heading(doc, "3", "Ответы на вопросы теоретической части")
    for number, title, items in THEORY:
        rb.subheading(doc, number, title)
        for i, (question, answer) in enumerate(items, start=1):
            rb.para(doc, f"{i} {question}")
            rb.para(doc, answer)
            rb.blank(doc)

    for number, title, filename, items in PARTS:
        queries = read_queries(filename)
        if len(queries) != len(items):
            raise SystemExit(
                f"{filename}: запросов {len(queries)}, пунктов задания {len(items)}")
        rb.heading(doc, number, title)
        for i, (item, query) in enumerate(zip(items, queries), start=1):
            rb.para(doc, f"{i}. {item}")
            rb.blank(doc)
            rb.code(doc, query)
            rb.blank(doc)

    rb.heading(doc, "8", "Вывод")
    for text in CONCLUSION:
        rb.para(doc, text)

    rb.save(doc, OUT)


if __name__ == "__main__":
    build()

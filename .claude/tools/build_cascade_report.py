def split_script():
    text = SCRIPT.read_text(encoding="utf-8").rstrip()
    head, _, tail = text.partition("DELIMITER $$")
    return head.rstrip(), ("DELIMITER $$" + tail).strip()


def build():
    tables_sql, trigger_sql = split_script()

    doc = rb.new_document()
    rb.title_page(doc, 6, TOPIC)

    rb.heading(doc, "1", "Цель работы")
    rb.para(doc, GOAL)

    rb.heading(doc, "2", "Задание")
    for i, text in enumerate(TASKS, start=1):
        rb.para(doc, f"{i}. {text}")
    rb.blank(doc)
    rb.para(doc, SCOPE_NOTE)

    rb.heading(doc, "3", "Краткие теоретические сведения")
    for text in THEORY:
        rb.para(doc, text)

    rb.heading(doc, "4", "Структура базы данных")
    rb.caption(doc, "Таблица 1 - Состав базы данных Biblioteka")
    rb.table(doc, STRUCTURE_HEADER, STRUCTURE, [3.8, 9.7, 3.0])
    rb.blank(doc)
    for text in STRUCTURE_NOTE:
        rb.para(doc, text)

    rb.heading(doc, "5", "Каскадные правила")
    rb.caption(doc, "Таблица 2 - Поведение дочерних записей")
    rb.table(doc, RULES_HEADER, RULES, [4.6, 6.6, 5.3])
    rb.blank(doc)
    for text in RULES_NOTE:
        rb.para(doc, text)

    rb.heading(doc, "6", "SQL-код создания базы данных и таблиц")
    rb.code(doc, tables_sql)

    rb.heading(doc, "7", "SQL-код триггера")
    for text in TRIGGER_NOTE:
        rb.para(doc, text)
    rb.blank(doc)
    rb.code(doc, trigger_sql)

    rb.heading(doc, "8", "Проверка работы каскадных операций")
    rb.para(doc, CHECK_NOTE)
    rb.blank(doc)
    rb.caption(doc, "Таблица 3 - Результаты проверки")
    rb.table(doc, CHECK_HEADER, CHECK, [7.3, 9.2])
    rb.blank(doc)
    rb.para(doc, CHECK_TAIL)

    rb.heading(doc, "9", "Вывод")
    for text in CONCLUSION:
        rb.para(doc, text)

    rb.save(doc, OUT)


if __name__ == "__main__":
    build()
